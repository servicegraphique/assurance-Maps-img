import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { JSDOM } from 'jsdom';
const dom = new JSDOM('<!doctype html><div id="host"></div>', { url: 'http://localhost:8080/', runScripts: 'outside-only', pretendToBeVisual: true });
const { window } = dom;
window.SVGSVGElement.prototype.createSVGRect = () => ({});
Object.defineProperty(window.HTMLElement.prototype, 'clientWidth', { configurable: true, get: () => 800 });
Object.defineProperty(window.HTMLElement.prototype, 'clientHeight', { configurable: true, get: () => 440 });
for (const key of ['window', 'document', 'navigator', 'HTMLElement', 'Element', 'Node']) Object.defineProperty(globalThis, key, { value: window[key], configurable: true });
for (const path of ['leaflet/leaflet.js', 'turf/turf.min.js', 'osmtogeojson/osmtogeojson.js', 'geoman/leaflet-geoman.min.js']) window.eval(readFileSync(new URL(`../vendor/${path}`, import.meta.url), 'utf8'));
const L = window.L;
let map; const factory = L.map; L.map = (...args) => (map = factory(...args));
const ring = [[2,48],[2.0002,48],[2.0002,48.0001],[2,48.0001],[2,48]];
const feature = { type:'Feature', properties: { contenance: 175 }, geometry: { type: 'Polygon', coordinates: [ring] } };
let calls = [];
globalThis.fetch = async url => {
  calls.push(String(url));
  const u = new URL(url, 'http://localhost:8080');
  if (u.hostname === 'overpass-api.de') return new Response('failed', { status: 503 });
  if (u.hostname === 'apicarto.ign.fr') return Response.json({ type: 'FeatureCollection', features: [feature] });
  if (u.searchParams.get('typeName') === 'BDTOPO_V3:equipement_de_transport') return Response.json({ type: 'FeatureCollection', features: [] });
  return Response.json({ type: 'FeatureCollection', features: [feature] });
};
const { createSiteMap } = await import('../js/site-map.js');
const host = window.document.querySelector('#host');
const site = createSiteMap(host, { lat: 48, lon: 2 });
const wait = async f => { for (let i = 0; i < 100; i++) { if (f()) return; await new Promise(r => setTimeout(r, 10)); } throw new Error('timeout'); };
await wait(() => host.querySelector('.site-status').textContent.includes('indisponible'));
assert.match(host.querySelector('.site-status').textContent, /Bâtiments.*1 polygone/);
assert.match(host.querySelector('.site-status').textContent, /Parkings.*indisponible/);
const layers = []; map.eachLayer(l => { if (l instanceof L.GeoJSON) l.eachLayer(child => layers.push(child)); });
assert.equal(layers.length, 2);
layers[1].fire('click', { originalEvent: { stopPropagation() {} } });
assert.match(host.querySelector('.site-details').textContent, /Contenance cadastrale officielle : 175 m²/);
layers[0].fire('click', { originalEvent: { stopPropagation() {} } });
assert.match(host.querySelector('.site-details').textContent, /Toiture estimée à 30°/);
const click = node => node.dispatchEvent(new window.MouseEvent('click', { bubbles: true }));
const button = label => [...host.querySelectorAll('button')].find(b => b.textContent === label);
click(button('Dessiner une surface'));
assert.equal(map.pm.Draw.Polygon.enabled(), true);
assert.ok(button('Annuler le dessin'));
// Geoman reçoit les clics géographiques, puis la fermeture du premier sommet.
for (const point of [[48,2], [48,2.0002], [48.0001,2.0002], [48.0001,2]]) {
  map.fire('click', { latlng: L.latLng(point), originalEvent: new window.MouseEvent('click') });
}
const polygonDraw = map.pm.Draw.Polygon;
assert.ok(polygonDraw._markers.length >= 3, 'sommets réellement placés');
polygonDraw._markers[0].fire('click', { originalEvent: new window.MouseEvent('click') });
assert.equal(polygonDraw.enabled(), false);
assert.match(host.querySelector('.site-details').textContent, /dessin manuel/);
assert.match(host.querySelector('.site-details').textContent, /Surface au sol/);
let manual; map.eachLayer(l => { if (l instanceof L.Polygon && l.options.color === '#9333ea') manual = l; });
assert.ok(manual);
click(button('Modifier le dessin'));
assert.equal(manual.pm.enabled(), true);
const before = host.querySelector('.site-details').textContent;
manual.setLatLngs([[48,2], [48,2.0004], [48.0001,2.0004], [48.0001,2]]);
manual.fire('pm:change');
assert.notEqual(host.querySelector('.site-details').textContent, before);
click(button('Terminer la modification'));
assert.equal(manual.pm.enabled(), false);
click(button('Supprimer le dessin'));
assert.equal(map.hasLayer(manual), false);
assert.match(host.querySelector('.site-details').textContent, /Dessin supprimé/);
// Une copie automatique est modifiable sans altérer la couche d'origine.
layers[0].fire('click', { originalEvent: { stopPropagation() {} } });
click(button('Corriger une copie du polygone sélectionné'));
let copy; map.eachLayer(l => { if (l instanceof L.Polygon && l.options.color === '#9333ea') copy = l; });
assert.ok(copy && copy.pm.enabled());
assert.ok(map.hasLayer(layers[0]));
click(button('Terminer la modification'));
click(button('Supprimer le dessin'));
assert.ok(map.hasLayer(layers[0]));
click(button('Dessiner une surface'));
click(button('Annuler le dessin'));
assert.equal(map.pm.Draw.Polygon.enabled(), false);
click(button('Dessiner une surface'));
document.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
assert.equal(map.pm.Draw.Polygon.enabled(), false);
click(button('Choisir un point sur la carte'));
map.fire('click', { latlng: L.latLng(48.01,2.01) });
await wait(() => calls.length === 8);
assert.ok(calls.some(url => url.includes('48.01')));
site.destroy();
// Le dessin manuel reste disponible même sans convertisseur OSM ni coordonnées.
delete window.osmtogeojson; host.replaceChildren();
const fallback = createSiteMap(host, null);
click(button('Dessiner une surface'));
assert.equal(map.pm.Draw.Polygon.enabled(), true);
const beforeCalls = calls.length;
fallback.setPosition({ lat: 48, lon: 2 });
assert.equal(map.pm.Draw.Polygon.enabled(), true);
assert.equal(calls.length, beforeCalls, 'la position tardive ne doit pas interrompre le dessin');
assert.equal(button('Analyser le GPS de l’établissement').disabled, false);
click(button('Annuler le dessin'));
fallback.destroy();
console.log('Analyse de site : sources partielles, sélection, dessin et clic validés.');
